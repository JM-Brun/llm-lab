#!/usr/bin/env python3
"""Render selected computational-graph views as bilingual Mermaid fragments.

The YAML registry remains the only authoring source. Generated fragments are
included by the relevant Quarto lessons; they are not edited by hand.
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[2]
REGISTRY = ROOT / "data" / "computational-graph.yml"
OUTPUT_DIR = ROOT / "site" / "includes"
RENDERED_VIEWS = (
    "representation-pipeline",
    "transformer-block",
    "generation",
    "inference-execution",
    "observed-target-scoring",
    "training",
)
LANGUAGES = ("fr", "en")


def _mermaid_text(value: str) -> str:
    """Escape text for a quoted Mermaid node or edge label."""
    return value.replace("&", "&amp;").replace('"', "#quot;").replace("\n", "<br/>")


def render_view(registry: dict[str, Any], view_id: str, language: str) -> str:
    """Render one named view, preserving its selected nodes and typed edges."""
    if language not in LANGUAGES:
        raise ValueError(f"Unsupported language: {language}")

    views = {view["id"]: view for view in registry["views"]}
    nodes = {node["id"]: node for node in registry["nodes"]}
    relation_types = registry["relation_types"]
    view = views.get(view_id)
    if view is None:
        raise ValueError(f"Unknown computational graph view: {view_id}")

    selected_nodes = view["nodes"]
    selected_edges = view["edges"]
    missing_nodes = set(selected_nodes) - nodes.keys()
    if missing_nodes:
        raise ValueError(f"{view_id}: unknown nodes: {sorted(missing_nodes)}")

    edges = {edge["id"]: edge for edge in registry["edges"]}
    missing_edges = set(selected_edges) - edges.keys()
    if missing_edges:
        raise ValueError(f"{view_id}: unknown edges: {sorted(missing_edges)}")

    labels = {node_id: nodes[node_id]["labels"][language] for node_id in selected_nodes}
    lines = [
        "<!-- Generated by site/tools/render_computational_graph.py; do not edit by hand. -->",
        f"::: {{.callout-note collapse=\"true\" title=\"{view['labels'][language]}\"}}",
        view["descriptions"][language],
        "",
        "\`\`\`{mermaid}",
        "flowchart LR",
    ]

    shape_by_kind = {
        "data": ("([", "])"),
        "operation": ("[", "]"),
        "control": ("{", "}"),
        "policy": ("[/", "/]"),
    }
    for node_id in selected_nodes:
        node = nodes[node_id]
        opening, closing = shape_by_kind[node["kind"]]
        label = _mermaid_text(labels[node_id])
        lines.append(f'    n_{node_id}{opening}"{label}"{closing}')

    for edge_id in selected_edges:
        edge = edges[edge_id]
        if edge["from"] not in labels or edge["to"] not in labels:
            raise ValueError(f"{view_id}: edge {edge_id} has an endpoint outside the view")
        relation = relation_types[edge["type"]]["labels"][language]
        lines.append(
            f'    n_{edge["from"]} -->|"{_mermaid_text(relation)}"| n_{edge["to"]}'
        )

    lines.extend(["\`\`\`", ":::", ""])
    return "\n".join(lines)


def render_all(registry: dict[str, Any], output_dir: Path) -> list[Path]:
    """Write the selected bilingual view fragments and return their paths."""
    output_dir.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for language in LANGUAGES:
        for view_id in RENDERED_VIEWS:
            path = output_dir / f"generated-computational-graph-{language}-{view_id}.qmd"
            path.write_text(render_view(registry, view_id, language), encoding="utf-8")
            written.append(path)
    return written


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--registry", type=Path, default=REGISTRY)
    parser.add_argument("--output-dir", type=Path, default=OUTPUT_DIR)
    args = parser.parse_args()

    registry = yaml.safe_load(args.registry.read_text(encoding="utf-8"))
    written = render_all(registry, args.output_dir)
    print(f"Rendered {len(written)} bilingual computational graph fragments.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
