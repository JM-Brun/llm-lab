"""Tests for the registry-driven computational graph fragments."""

from __future__ import annotations

import copy
import runpy
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[2]
MODULE: dict[str, Any] = runpy.run_path(
    str(ROOT / "site" / "tools" / "render_computational_graph.py"),
    run_name="computational_graph_renderer_test",
)
REGISTRY = yaml.safe_load(
    (ROOT / "data" / "computational-graph.yml").read_text(encoding="utf-8")
)


def test_render_view_uses_localized_node_and_relation_labels() -> None:
    render_view = MODULE["render_view"]

    french = render_view(REGISTRY, "generation", "fr")
    english = render_view(REGISTRY, "generation", "en")

    assert "flowchart LR" in french
    assert "Contexte en identifiants" in french
    assert "Token-ID context" in english
    assert "sélectionne" in french
    assert "selects" in english
    assert "n_generated-token" in french


def test_all_selected_views_render_for_both_languages(tmp_path: Path) -> None:
    render_all = MODULE["render_all"]
    rendered_views = MODULE["RENDERED_VIEWS"]

    paths = render_all(REGISTRY, tmp_path)

    assert len(paths) == len(rendered_views) * 2
    for path in paths:
        content = path.read_text(encoding="utf-8")
        assert "Generated by site/tools/render_computational_graph.py" in content
        assert "flowchart LR" in content
        assert content.count("-->|") > 0
        assert content.endswith(":::\n")


def test_renderer_rejects_an_edge_outside_its_view() -> None:
    render_view = MODULE["render_view"]
    registry = copy.deepcopy(REGISTRY)
    view = next(item for item in registry["views"] if item["id"] == "generation")
    view["nodes"].remove("generated-token")

    try:
        render_view(registry, "generation", "en")
    except ValueError as error:
        assert "endpoint outside the view" in str(error)
    else:
        raise AssertionError("An edge outside the selected view must be rejected.")
